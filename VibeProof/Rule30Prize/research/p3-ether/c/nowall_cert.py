# Certificate that no wall exists for attachment column a at width b (12x3 ether):
# for every node v = phi * 2^b + r (phi < 3, r < 2^b) a move z(v) and a distance d(v) with
#   d(v) = 0  -> v violates U (ether3 a phi = 0 and bit0(r) != ether3 (a+1) phi)
#   d(v) > 0  -> d(succ(v, z(v))) < d(v).
# Prints max distance; writes Lean data if an output file is given.
import sys
sys.set_int_max_str_digits(0)
from collections import deque
E = ["001","001","011","110","010","010","110","101","100","100","101","011"]
a = int(sys.argv[1]); b = int(sys.argv[2]); out = sys.argv[3] if len(sys.argv) > 3 else None
M = 1 << b; N = 3 * M
def stp(av, z, r):
    full = av | (r << 1) | (z << (b + 1))
    return (full ^ ((full >> 1) | (full >> 2))) & (M - 1)
def succ(v, z):
    phi, r = divmod(v, M)
    return ((phi + 1) % 3) * M + stp(int(E[a][phi]), z, r)
def viol(v):
    phi, r = divmod(v, M)
    return E[a][phi] == '0' and (r & 1) != int(E[(a + 1) % 12][phi])
pred = [[] for _ in range(N)]
for v in range(N):
    for z in (0, 1):
        pred[succ(v, z)].append((v, z))
d = [-1] * N; zz = [0] * N; dq = deque()
for v in range(N):
    if viol(v): d[v] = 0; dq.append(v)
while dq:
    u = dq.popleft()
    for (v, z) in pred[u]:
        if d[v] < 0: d[v] = d[u] + 1; zz[v] = z; dq.append(v)
unreached = sum(1 for v in range(N) if d[v] < 0)
print(f"a={a} b={b}: nodes {N}, unreached {unreached}, max distance {max(d)}")
if out and unreached == 0:
    assert max(d) < 32
    with open(out, 'w') as f:
        f.write(f"-- no-wall certificate, attachment column {a}, width {b} (generated by nowall_cert.py)\n")
        for phi in range(3):
            dT = sum(d[phi * M + r] << (5 * r) for r in range(M))
            zT = sum(zz[phi * M + r] << r for r in range(M))
            f.write(f"def nw{a}_{b}_d{phi} : Nat := {dT}\n")
            f.write(f"def nw{a}_{b}_z{phi} : Nat := {zT}\n")
