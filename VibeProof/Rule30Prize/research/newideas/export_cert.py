# Export a strip certificate (from cert.py) as Lean data.
import sys
sys.set_int_max_str_digits(0)
exec(open('cert.py').read().split("if __name__ == '__main__':")[0])
w = sys.argv[1]; b = int(sys.argv[2]); name = sys.argv[3]
cert = certify(w, b)
assert cert is not None
nodes, adj, rank, pos, words = cert
assert check(w, b, cert) == "OK"
P = len(w)
nr = max(rank.values()) + 1
rk = [0] * (P << b); ps = [0] * (P << b)
for (phi, s), r in rank.items():
    rk[phi * (1 << b) + s] = r
    ps[phi * (1 << b) + s] = pos[(phi, s)]
per = [1] * nr; wd = [[False]] * nr
for r, u in words.items():
    per[r] = len(u); wd[r] = [bool(x) for x in u]
# sanity: pos < per
for (phi, s), r in rank.items():
    assert ps[phi * (1 << b) + s] < per[r]
lw = 'false' if True else ''
def bl(xs): return '[' + ', '.join('true' if x else 'false' for x in xs) + ']'
assert max(rk) < 65536 and max(ps) < 256 and max(per) < 256 and max(len(u) for u in wd) <= 64
rankP = sum(r << (16 * i) for i, r in enumerate(rk))
posP = sum(p << (8 * i) for i, p in enumerate(ps))
perP = sum(m << (8 * r) for r, m in enumerate(per))
wordP = sum((1 << (64 * r + j)) for r, u in enumerate(wd) for j, x in enumerate(u) if x)
with open(f'lean/Cert_{name}.lean', 'w') as f:
    f.write(f"-- certificate for w = {w}, strip width b = {b}; generated by export_cert.py\n")
    f.write(f"def {name}_w : List Bool := {bl([c == '1' for c in w])}\n")
    f.write(f"def {name}_b : Nat := {b}\n")
    f.write(f"def {name}_nranks : Nat := {nr}\n")
    f.write(f"def {name}_rankP : Nat := {rankP}\n")
    f.write(f"def {name}_posP : Nat := {posP}\n")
    f.write(f"def {name}_perP : Nat := {perP}\n")
    f.write(f"def {name}_wordP : Nat := {wordP}\n")
print("exported", name, "nodes", P << b, "ranks", nr, "nontrivial words", sorted(set(''.join('1' if x else '0' for x in u) for u in wd)))
